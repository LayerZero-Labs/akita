#![cfg(feature = "labinius-sis")]

use akita_params::sis::labinius::{
    LabiniusCommitmentModulus, LabiniusRingDegree, LabiniusWidthCell, LabiniusWidthCutoff,
    LABINIUS_COMMITMENT_PRIME_WIDTH_TABLE, LABINIUS_COMMITMENT_PRIME_WIDTH_TABLE_DIGEST,
};
use akita_sis_estimator::{
    labinius_width_table::certified_rows,
    width_table::{
        generate_infinity_width_rows, validate_infinity_width_rows, InfinityWidthOrigin,
        InfinityWidthTableConfig,
    },
    AkitaModulusProfileId, SisSecurityPolicy,
};
use sha3::{Digest, Sha3_256};

const CSV: &str = include_str!("../data/labinius_commitment_prime_infinity_width.csv");
const COEFF_LINF_BOUND: u64 = 1_506_960;
/// Smallest rank with a certified positive width.
const MIN_RANK: u32 = 3;

/// The checked-in rows are what the search produces under the default policy
/// and cap, and the runtime cells and digest in `akita-params` are those rows.
#[test]
fn rows_regenerate_with_the_unchanged_policy_and_cap() {
    for line in CSV.lines().skip(1) {
        let fields = line.split(',').take(4).collect::<Vec<_>>();
        assert_eq!(
            fields,
            [
                "akita-infinity-width-v4",
                "phi243-bounded-w46-delta12",
                "162",
                "4"
            ]
        );
    }
    let rows = certified_rows().unwrap();
    let profile = AkitaModulusProfileId::Q25Plus14561;
    let config = InfinityWidthTableConfig {
        profiles: vec![profile],
        ring_dims: vec![648],
        coeff_linf_bounds: vec![COEFF_LINF_BOUND],
        max_rank: 4,
        explicit_origins: Some(vec![InfinityWidthOrigin {
            modulus_profile: profile,
            d: 648,
            coeff_linf_bound: COEFF_LINF_BOUND,
        }]),
        ..InfinityWidthTableConfig::default()
    };
    let candidates = generate_infinity_width_rows(&config).unwrap();
    assert_eq!(candidates.len(), 4);
    assert!(candidates
        .iter()
        .filter(|row| row.rank < MIN_RANK)
        .all(|row| row.max_width == 0));
    let regenerated = candidates
        .into_iter()
        .filter(|row| row.max_width > 0)
        .collect::<Vec<_>>();
    assert_eq!(rows, regenerated);
    validate_infinity_width_rows(rows).unwrap();
    assert_eq!(rows.len(), (MIN_RANK..=4).count());
    for row in rows {
        assert_eq!(row.modulus_profile, profile);
        assert_eq!(row.policy, SisSecurityPolicy::Quantum169BitADPS16);
        assert_eq!(row.d, 648);
        assert_eq!(row.coeff_linf_bound, COEFF_LINF_BOUND);
        assert_eq!(row.max_width, row.search_cap);
        assert_eq!(row.max_width, 6_400_000_000_000);
        assert!(row.hit_cap);
        assert!(row.next_costs.is_none());
    }
    let cells = rows
        .iter()
        .map(|row| LabiniusWidthCell {
            commitment_modulus: LabiniusCommitmentModulus::Q25Plus14561,
            ring_degree: LabiniusRingDegree::D648,
            rank: row.rank,
            coeff_linf_bound: row.coeff_linf_bound,
            max_width: row.max_width,
            cutoff: if row.hit_cap {
                LabiniusWidthCutoff::SearchCap
            } else {
                LabiniusWidthCutoff::Exact
            },
        })
        .collect::<Vec<_>>();
    assert_eq!(LABINIUS_COMMITMENT_PRIME_WIDTH_TABLE, cells);
    let digest: [u8; 32] = Sha3_256::digest(CSV.as_bytes()).into();
    assert_eq!(LABINIUS_COMMITMENT_PRIME_WIDTH_TABLE_DIGEST, digest);
}

/// Both q24 artifacts are regenerated by the actual certification path. This
/// catches numeric, status, ordering, model, and byte-format drift.
#[test]
fn q24_artifacts_regenerate_byte_for_byte_and_cover_the_requested_cells() {
    use akita_sis_estimator::labinius_width_table::{certified_max_width, q24, q24_certified_rows};
    assert_eq!(q24::generate_width_csv().unwrap(), q24::CSV);
    assert_eq!(q24::generate_cells_csv().unwrap(), q24::CELLS_CSV);
    let rows = q24_certified_rows().unwrap();
    assert_eq!(rows.len(), 6);
    for eta in q24::BOUNDS {
        for rank in 2..=4 {
            let cutoff = certified_max_width(q24::PROFILE, 648, rank, eta).unwrap();
            assert_eq!(
                cutoff,
                if rank == 2 {
                    None
                } else {
                    Some(6_400_000_000_000)
                }
            );
        }
    }
    for row in rows {
        assert_eq!(row.policy, SisSecurityPolicy::Quantum169BitADPS16);
        assert!(row.hit_cap);
        assert_eq!(row.max_width, 6_400_000_000_000);
        assert!(row.next_costs.is_none());
    }
    assert_eq!(q24::CELLS_CSV.lines().count(), 28);
    assert_eq!(
        q24::PROFILE.modulus(),
        num_bigint::BigUint::from(14_253_409u32)
    );
    assert_eq!(AkitaModulusProfileId::parse("q24").unwrap(), q24::PROFILE);
    assert_eq!(
        AkitaModulusProfileId::parse("Q24Minus2523807").unwrap(),
        q24::PROFILE
    );
    assert_eq!(
        LabiniusCommitmentModulus::Q24Minus2523807.modulus(),
        (1 << 24) - 2_523_807
    );
    for (weight, eta) in [46, 64, 77].into_iter().zip(q24::BOUNDS) {
        assert_eq!(4 * (2 * weight) * 4_095, eta);
    }
}

/// These are completed pinned reference runs, used only as discovery goldens.
/// The independently regenerated proven-pruned artifacts above certify widths.
#[test]
fn q24_quantum_discovery_crosschecks_the_reference_runs() {
    use akita_sis_estimator::{
        estimate, scalar_sis_from_ring, Adps16Mode, CostValue, EstimateConfig, ReductionCostModel,
    };
    let config = EstimateConfig {
        red_cost_model: ReductionCostModel::Adps16 {
            mode: Adps16Mode::Quantum,
        },
        ..EstimateConfig::lattice_estimator_parity()
    };
    for (rank, width, eta, bits, beta) in [
        (2, 4_096, 1_506_960, 126.14, 476),
        (2, 8_192, 1_506_960, 126.14, 476),
        (3, 4_096, 1_506_960, 212.795, 803),
        (3, 8_192, 1_506_960, 212.795, 803),
        (3, 4_096, 2_522_520, 197.425, 745),
    ] {
        let params = scalar_sis_from_ring(
            AkitaModulusProfileId::Q24Minus2523807,
            648,
            rank,
            width,
            eta,
        )
        .unwrap();
        assert_eq!(params.n, rank * 648);
        assert_eq!(params.m, Some(u64::from(width) * 648));
        let cost = estimate(&params, &config).unwrap();
        let CostValue::Finite(value) = cost.rop else {
            panic!("discovery must return a finite attack")
        };
        assert!(
            (value.log2 - bits).abs() < 1e-6,
            "{rank}/{width}/{eta}: {cost:?}"
        );
        assert_eq!(cost.beta, Some(beta));
    }
}
