//! Generate the Σ-binding SIS width table (`specs/whiteout-akita.md` §5.5.2):
//! the largest Module-SIS-hard width per module rank of a matrix the Whiteout
//! Σ-protocol opens, at its coefficient-ℓ∞ collision radius
//! (`akita_params::sis::sigma_binding::sigma_binding_radius`), under the
//! ADPS16 quantum model of Akita's ℓ∞ table.
//!
//! Search mode writes the certified CSV and the runtime cells
//! (`akita-params/src/sis/sigma_binding/generated.rs`); `--from-csv` rewrites
//! the runtime cells from the checked-in CSV without a lattice search.
//!
//! ```text
//! cargo run --release -p akita-sis-estimator --features zk,parallel \
//!     --example sigma_binding_width_table -- [--from-csv] [--dims 64,128,256,512]
//! ```

use akita_params::sis::sigma_binding::sigma_binding_radius;
use akita_sis_estimator::{
    width_table::{
        generate_infinity_width_rows, validate_infinity_width_rows, InfinityWidthOrigin,
        InfinityWidthRow, InfinityWidthTableConfig, INFINITY_WIDTH_EVALUATOR_ID,
    },
    AkitaModulusProfileId,
};
use sha3::{Digest, Sha3_256};
use std::{
    env, fs,
    path::{Path, PathBuf},
    process,
    time::Instant,
};

const MODULUS_PROFILE: AkitaModulusProfileId = AkitaModulusProfileId::Q128OffsetA7F7;
const CSV_NAME: &str = "sigma_binding_infinity_width.csv";
const MAX_RANK: u32 = 20;

struct Args {
    output: PathBuf,
    rust_output: PathBuf,
    from_csv: bool,
    dims: Vec<u32>,
}

fn main() {
    let args = Args::parse();
    let radius = u64::try_from(sigma_binding_radius())
        .unwrap_or_else(|_| fatal("the Σ binding radius exceeds u64"));
    if args.from_csv {
        let csv = fs::read(&args.output)
            .unwrap_or_else(|error| fatal(&format!("read {}: {error}", args.output.display())));
        let rows = parse_csv(&String::from_utf8_lossy(&csv));
        write_file(&args.rust_output, &runtime_table(&rows, &csv, radius));
        return;
    }
    let config = InfinityWidthTableConfig {
        profiles: vec![MODULUS_PROFILE],
        ring_dims: args.dims.clone(),
        coeff_linf_bounds: vec![radius],
        max_rank: MAX_RANK,
        explicit_origins: Some(
            args.dims
                .iter()
                .map(|&d| InfinityWidthOrigin {
                    modulus_profile: MODULUS_PROFILE,
                    d,
                    coeff_linf_bound: radius,
                })
                .collect(),
        ),
        ..InfinityWidthTableConfig::default()
    };
    let started = Instant::now();
    let rows = generate_infinity_width_rows(&config)
        .unwrap_or_else(|error| fatal(&format!("generation failed: {error}")));
    validate_infinity_width_rows(&rows)
        .unwrap_or_else(|error| fatal(&format!("certificate validation failed: {error}")));
    let mut csv = format!("estimator_id,{}\n", InfinityWidthRow::csv_header());
    for row in &rows {
        csv.push_str(&format!(
            "{INFINITY_WIDTH_EVALUATOR_ID},{}\n",
            row.to_csv_record()
        ));
    }
    write_file(&args.output, &csv);
    write_file(
        &args.rust_output,
        &runtime_table(&rows, csv.as_bytes(), radius),
    );
    eprintln!(
        "wrote {} Σ-binding row(s) in {:.3}s",
        rows.len(),
        started.elapsed().as_secs_f64()
    );
}

fn parse_csv(csv: &str) -> Vec<InfinityWidthRow> {
    let mut lines = csv.lines();
    let expected = format!("estimator_id,{}", InfinityWidthRow::csv_header());
    if lines.next() != Some(expected.as_str()) {
        fatal("unexpected CSV header");
    }
    let rows = lines
        .map(|line| {
            let record = line
                .strip_prefix(&format!("{INFINITY_WIDTH_EVALUATOR_ID},"))
                .unwrap_or_else(|| fatal("a CSV row has another estimator id"));
            InfinityWidthRow::from_csv_record(record)
                .unwrap_or_else(|error| fatal(&format!("invalid CSV row: {error}")))
        })
        .collect::<Vec<_>>();
    validate_infinity_width_rows(&rows)
        .unwrap_or_else(|error| fatal(&format!("certificate validation failed: {error}")));
    rows
}

/// The runtime cells: per dimension, the largest width by rank.
fn runtime_table(rows: &[InfinityWidthRow], csv: &[u8], radius: u64) -> String {
    let mut dims = rows.iter().map(|row| row.d).collect::<Vec<_>>();
    dims.sort_unstable();
    dims.dedup();
    let mut output = format!(
        "// AUTO-GENERATED by crates/akita-sis-estimator/examples/sigma_binding_width_table.rs -- do not edit by hand.\n\
         // Source: crates/akita-sis-estimator/data/{CSV_NAME}\n\
         // Largest Module-SIS-hard width per rank at the Σ collision radius, coefficient\n\
         // L-infinity, ADPS16 quantum model, modulus profile Q128OffsetA7F7.\n\n\
         use super::super::ajtai_key::SisModulusProfileId;\n\n\
         /// The radius the cells were generated at.\n\
         pub(super) const SIGMA_BINDING_RADIUS: u128 = {radius};\n\n\
         /// Widths per rank (`widths[rank - 1]`) of a `d`-dimensional matrix at\n\
         /// [`SIGMA_BINDING_RADIUS`].\n\
         #[rustfmt::skip]\n\
         pub(super) fn sigma_binding_max_widths(profile: SisModulusProfileId, d: u32) -> Option<&'static [u64]> {{\n\
         \x20   if profile != SisModulusProfileId::Q128OffsetA7F7 {{\n\
         \x20       return None;\n\
         \x20   }}\n\
         \x20   match d {{\n"
    );
    for d in dims {
        let mut cells = rows
            .iter()
            .filter(|row| row.d == d)
            .map(|row| (row.rank, row.max_width))
            .collect::<Vec<_>>();
        cells.sort_unstable();
        let widths = cells
            .iter()
            .map(|(_, width)| width.to_string())
            .collect::<Vec<_>>()
            .join(", ");
        output.push_str(&format!("        {d} => Some(&[{widths}]),\n"));
    }
    let digest: [u8; 32] = Sha3_256::digest(csv).into();
    output.push_str(&format!(
        "        _ => None,\n    }}\n}}\n\n\
         /// SHA3-256 of the certified CSV the cells come from.\n\
         #[cfg(test)]\n\
         #[rustfmt::skip]\n\
         pub(super) const SIGMA_BINDING_TABLE_DIGEST: [u8; 32] = {digest:?};\n"
    ));
    output
}

fn write_file(path: &Path, contents: &str) {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .unwrap_or_else(|error| fatal(&format!("create output directory failed: {error}")));
    }
    fs::write(path, contents)
        .unwrap_or_else(|error| fatal(&format!("write {} failed: {error}", path.display())));
}

impl Args {
    fn parse() -> Self {
        let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        let mut parsed = Self {
            output: manifest.join("data").join(CSV_NAME),
            rust_output: manifest.join("../akita-params/src/sis/sigma_binding/generated.rs"),
            from_csv: false,
            dims: vec![64, 128, 256, 512],
        };
        let mut args = env::args().skip(1);
        while let Some(arg) = args.next() {
            match arg.as_str() {
                "--help" | "-h" => usage(0),
                "--from-csv" => parsed.from_csv = true,
                "--dims" => {
                    let value = args.next().unwrap_or_else(|| usage(2));
                    parsed.dims = value
                        .split(',')
                        .map(|entry| {
                            entry
                                .trim()
                                .parse()
                                .unwrap_or_else(|_| fatal("invalid dimension"))
                        })
                        .collect();
                }
                _ => usage(2),
            }
        }
        parsed
    }
}

fn usage(code: i32) -> ! {
    eprintln!("usage: sigma_binding_width_table [--from-csv] [--dims 64,128,256,512]");
    process::exit(code);
}

fn fatal(message: &str) -> ! {
    eprintln!("error: {message}");
    process::exit(2);
}
